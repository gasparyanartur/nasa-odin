import { test, expect } from '@playwright/test';

test('real Gale layers, route comparison, walkable HUD and reset',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Gale · Bradbury',exact:false}).first().click();
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:/Plan excursion/}).click();
  await expect(page.getByRole('button',{name:'Compare routes →'})).toBeEnabled();
  await expect(page.getByText('REMS air temperature')).toBeVisible();
  await page.getByLabel('Slope',{exact:true}).check();
  const map=page.getByRole('img',{name:'Gale terrain selection map'});
  const bounds=(await map.boundingBox())!;
  await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2);
  await expect(page.getByLabel('Terrain inspection')).toContainText('-450');
  await page.getByRole('button',{name:'Compare routes →'}).click();
  await expect(page.locator('.route-card')).toHaveCount(2,{timeout:60000});
  await expect(page.locator('.route-card').first()).toContainText('including return');
  await page.screenshot({path:info.outputPath('gale-planner.png'),fullPage:true});
  await page.locator('.route-card').last().click();
  await page.getByRole('button',{name:'Walk selected route →'}).click();
  await expect(page.getByRole('img',{name:'Astronaut minimap'})).toBeVisible();
  await page.getByLabel('Simulation pace').selectOption('20');
  await expect(page.locator('.walking-scene canvas')).toBeVisible();
  await page.waitForTimeout(1500);
  const before=await page.getByTestId('position').textContent();
  await page.locator('.walking-scene canvas').click({position:{x:450,y:350}});
  await expect(page.locator('.walk-instructions')).toHaveCount(0);
  await page.keyboard.down('w');
  await expect(page.getByTestId('position')).not.toHaveText(before!,{timeout:10000});
  await page.waitForTimeout(2200);await page.keyboard.up('w');await page.keyboard.press('Escape');
  await expect(page.getByTestId('position')).not.toHaveText(before!);
  expect(Number((await page.getByTestId('elapsed').textContent())!.split(' ')[0])).toBeGreaterThan(.5);
  await expect(page.locator('.walk-instructions')).toBeVisible();
  const paused=await page.getByTestId('elapsed').textContent();await page.waitForTimeout(400);await expect(page.getByTestId('elapsed')).toHaveText(paused!);
  // Regression: adding the texture after first paint must recompile the material.
  // A valid scene must show ground detail, not a single untextured flat color.
  const ground=(await page.locator('.walking-scene canvas').screenshot()).toString('base64');
  const colors=await page.evaluate(async b64=>{
    const img=new Image();img.src=`data:image/png;base64,${b64}`;await img.decode();
    const c=document.createElement('canvas');c.width=img.width;c.height=img.height;
    const ctx=c.getContext('2d')!;ctx.drawImage(img,0,0);
    const pixels=ctx.getImageData(Math.floor(c.width*.1),Math.floor(c.height*.65),Math.floor(c.width*.7),40).data;
    const values=new Set<string>();for(let i=0;i<pixels.length;i+=4)values.add(`${pixels[i]},${pixels[i+1]},${pixels[i+2]}`);
    return values.size;
  },ground);
  expect(colors).toBeGreaterThan(8);
  await page.screenshot({path:info.outputPath('gale-walking-hud.png')});
  await page.getByRole('button',{name:'Reset excursion',exact:true}).click();
  await expect(page.getByRole('button',{name:'Compare routes →'})).toBeVisible();
  await expect(page.locator('.route-card')).toHaveCount(0);
  await page.getByRole('button',{name:'＋ Exclusion',exact:true}).click();
  const b=(await map.boundingBox())!;
  await map.click({position:{x:b.width/2,y:b.height/2}});
  await page.getByRole('button',{name:'Compare routes →'}).click();
  await expect(page.getByRole('alert')).toContainText('blocked',{timeout:30000});
  await page.getByRole('button',{name:'Clear exclusions'}).click();
  await page.route('**/api/routes',route=>route.abort());
  await page.getByRole('button',{name:'Compare routes →'}).click();
  await expect(page.getByRole('alert')).toContainText('Route planning is temporarily unavailable');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:info.outputPath('gale-mobile.png'),fullPage:true});
  expect(errors).toEqual([]);
});
