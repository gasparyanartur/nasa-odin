import { test,expect } from '@playwright/test';
const nav=(page:import('@playwright/test').Page)=>page.getByRole('navigation',{name:'Main navigation'});

test('direct geological science example, linked profiles, provenance and surface destination',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/?demo=yellowknife');
  await expect(page.getByRole('region',{name:'Guided science example'})).toBeVisible();
  await expect(page.locator('.endpoint').nth(1)).toContainText('450 E · -10 N');
  await expect(page.locator('.science-target.selected')).toContainText('Yellowknife Bay entry');
  const workspace=page.getByRole('region',{name:'Gale route planner'});
  await expect(workspace.getByLabel('Geological units',{exact:true})).toBeChecked();
  await expect(workspace.getByLabel('Geology at inspection point')).toContainText('AHi');
  await expect(page.getByRole('button',{name:'Compare science routes →'})).toBeEnabled();
  await page.getByRole('button',{name:'Compare science routes →'}).click();
  await expect(page.locator('.route-card')).toHaveCount(2);
  await expect(page.getByRole('region',{name:'Explain route comparison'})).toBeVisible();
  await page.getByLabel('Profile distance',{exact:true}).fill('150');
  const terrain=page.getByRole('img',{name:'Gale terrain selection map'});
  await expect(terrain).not.toHaveAttribute('data-highlighted-edge','');
  await expect(page.getByLabel('Selected route segment')).toContainText('conservative terrain slope');
  await page.getByLabel('Route profile metric',{exact:true}).selectOption('slopeDeg');
  await expect(page.getByRole('img',{name:'Terrain slope profile of selected outbound route'})).toBeVisible();
  await page.getByRole('region',{name:'Explain route comparison'}).screenshot({path:info.outputPath('v03-route-explanation.png')});
  await page.getByRole('button',{name:'Show segment on map ↑'}).click();
  await expect(terrain).toBeInViewport({ratio:.5});
  await terrain.screenshot({path:info.outputPath('v03-profile-map.png')});
  await page.getByLabel('Inspect map data',{exact:true}).selectOption('geology');
  await expect(page.getByRole('region',{name:'Map data provenance'})).toContainText('1:20,000,000');
  await expect(page.getByRole('region',{name:'Map data provenance'})).toContainText('PUBLISHED GEOLOGICAL INTERPRETATION');
  await page.getByRole('region',{name:'Map data provenance'}).screenshot({path:info.outputPath('v03-provenance.png')});
  await page.getByLabel('Inspect map data',{exact:true}).selectOption('radiation');
  await expect(page.getByRole('region',{name:'Map data provenance'})).toContainText('not astronaut dose equivalent');
  await page.getByRole('button',{name:'Plan to Rocknest →',exact:true}).click();
  await expect(page.locator('.endpoint').nth(1)).toContainText('395 E · -30 N');
  await expect(page.locator('.route-card')).toHaveCount(0);
  await expect(terrain).toHaveAttribute('data-highlighted-edge','');
  await page.getByRole('button',{name:'Reset guided example',exact:true}).click();
  await expect(page.locator('.endpoint').nth(1)).toContainText('450 E · -10 N');
  await page.getByRole('button',{name:'Compare science routes →'}).click();
  await expect(page.locator('.route-card')).toHaveCount(2);
  await page.evaluate(()=>{document.querySelector('.mission-sidebar')!.scrollTop=0;document.querySelector('.terrain-workspace')!.scrollTop=0;});
  await page.screenshot({path:info.outputPath('v03-guided-planner.png')});
  await page.getByRole('button',{name:'Walk selected route →'}).click();
  await expect(page.locator('.walking-scene canvas')).toBeVisible();
  await expect(page.locator('.hud-heading')).toContainText('Yellowknife Bay entry');
  await page.screenshot({path:info.outputPath('v03-science-hud.png')});
  await page.getByRole('button',{name:'← Return to planner',exact:true}).click();
  await page.getByRole('button',{name:'Continue free exploration',exact:true}).click();
  await expect(page.getByRole('region',{name:'Guided science example'})).toHaveCount(0);
  await expect(page.locator('.route-card')).toHaveCount(2);
  await expect(page).not.toHaveURL(/demo=/);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>{document.querySelector('.mission-sidebar')!.scrollTop=0;document.querySelector('.terrain-workspace')!.scrollTop=0;window.scrollTo(0,0);});
  await page.screenshot({path:info.outputPath('v03-mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('one-click entry, inspectable regional geology, region isolation and data recovery',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/gale/height.f32',r=>r.abort());
  await page.goto('/');await page.getByRole('button',{name:'Start guided Gale example →'}).click();
  await expect(page.getByRole('alert')).toContainText('Local Gale data could not load');
  await expect(page.getByRole('button',{name:'Compare science routes →'})).toBeDisabled();
  await page.unroute('**/gale/height.f32');await page.getByRole('button',{name:'Retry local data'}).click();
  await expect(page.getByRole('button',{name:'Compare science routes →'})).toBeEnabled();
  await nav(page).getByRole('button',{name:/Explore/}).click();
  const explorer=page.locator('.explorer');
  await expect(explorer.getByLabel('Geological units',{exact:true})).toBeChecked();
  await explorer.getByRole('button',{name:'View geological context ↗'}).click();
  await explorer.getByRole('button',{name:/AHi Amazonian and Hesperian impact unit/}).click();
  await expect(explorer.getByLabel('Selected geological unit')).toContainText('Upturned');
  await explorer.getByText('Inspect mapped contacts',{exact:false}).click();
  await explorer.getByRole('button',{name:/Contact \d+ ·/}).first().click();
  await expect(explorer.getByLabel('Selected geological contact')).toContainText('Published classification');
  await page.waitForTimeout(1500);
  await page.screenshot({path:info.outputPath('v03-geology-globe.png')});
  await explorer.getByLabel('Geology opacity',{exact:true}).fill('60');
  await nav(page).getByRole('button',{name:/Plan excursion/}).click();
  await expect(page.getByRole('region',{name:'Gale route planner'}).getByLabel('Geology opacity',{exact:true})).toHaveValue('60');
  await nav(page).getByRole('button',{name:/Explore/}).click();
  await page.getByRole('region',{name:'Regions'}).getByRole('button',{name:/Jezero/}).click();
  await expect(nav(page).getByRole('button',{name:/Plan excursion/})).toBeDisabled();
  await expect(nav(page).getByRole('button',{name:/Surface HUD/})).toBeDisabled();
  await expect(explorer.getByLabel('Geological unit legend')).toContainText('Early Hesperian volcanic unit');
  await expect(explorer.getByLabel('Selected geological contact')).toHaveCount(0);
  await page.getByRole('button',{name:'Start guided Gale example →'}).click();
  await expect(page.locator('.science-target.selected')).toContainText('Yellowknife Bay entry');
  await expect(page.locator('.route-card')).toHaveCount(0);
  expect(errors).toEqual([]);
});
