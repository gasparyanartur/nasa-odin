test('tablet touch pinch, drag, tap inspection and placement share transformed coordinates',async({page},info)=>{
  await page.setViewportSize({width:1024,height:900});
  await page.goto('/?demo=yellowknife');
  const map=page.getByRole('img',{name:'Gale terrain selection map'});
  await expect(page.getByRole('button',{name:'Plan route',exact:true})).toBeEnabled();
  await map.scrollIntoViewIfNeeded();
  const box=(await map.boundingBox())!;
  const cdp=await page.context().newCDPSession(page);
  const point=(id:number,x:number,y:number)=>({id,x:box.x+box.width*x,y:box.y+box.height*y});
  const touch=(type:string,touchPoints:ReturnType<typeof point>[])=>cdp.send('Input.dispatchTouchEvent',{type:type as 'touchStart',touchPoints});
  await touch('touchStart',[point(1,.4,.5),point(2,.6,.5)]);
  await touch('touchMove',[point(1,.3,.5),point(2,.7,.5)]);
  await touch('touchEnd',[]);
  await expect.poll(async()=>Number(await map.getAttribute('data-zoom'))).toBeCloseTo(2,1);
  await touch('touchStart',[point(1,.5,.5)]);await touch('touchMove',[point(1,.6,.5)]);await touch('touchEnd',[]);
  // Dragging must not select a different science target or change the destination.
  await expect(page.locator('.endpoint').nth(1)).toContainText('450 E · -10 N');
  await touch('touchStart',[point(1,.5,.5)]);await touch('touchEnd',[]);
  await expect(page.getByLabel('Terrain inspection')).toContainText('137.440');
  await page.locator('.endpoint').nth(1).getByRole('button',{name:'Place',exact:true}).click();
  await map.scrollIntoViewIfNeeded();const next=(await map.boundingBox())!;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:1,x:next.x+next.width*.5,y:next.y+next.height*.5}]});
  await touch('touchEnd',[]);
  await expect(page.locator('.endpoint').nth(1)).toContainText('-100 E · 0 N');
  await page.getByRole('button',{name:'Full area',exact:true}).click();
  await expect(map).toHaveAttribute('data-zoom','1.00');
  await map.scrollIntoViewIfNeeded();
  const full=(await map.boundingBox())!;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{id:1,x:full.x+full.width*.725,y:full.y+full.height*.505}]});
  await touch('touchEnd',[]);
  await expect(page.locator('.science-target.selected')).toContainText('Yellowknife Bay entry');
  await page.screenshot({timeout:60_000,path:info.outputPath('v04-tablet-touch.png'),fullPage:true});
  await page.setViewportSize({width:800,height:700});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({timeout:60_000,path:info.outputPath('v04-tablet-mobile.png'),fullPage:true});
  const target=await page.getByRole('button',{name:'Zoom in local map'}).boundingBox();
  expect(target!.height).toBeGreaterThanOrEqual(28);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
