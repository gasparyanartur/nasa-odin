import { uiRoutes, uiStation, uiStationData, uiLayers, uiAssumptions } from './ui-helpers';
import { test, expect } from '@playwright/test';
const nav=(page:import('@playwright/test').Page)=>page.getByRole('navigation',{name:'Main navigation'});

test('numeric environmental maps, historical data and causal forecast share state without changing a mission',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/?demo=yellowknife');
  await uiRoutes(page);await page.getByRole('button',{name:'Compare routes',exact:true}).click();
  await expect(page.locator('.route-card')).toHaveCount(2);
  const route=await page.locator('.route-card.selected').textContent();
  await uiStation(page);
  await page.getByRole('button',{name:'Data & history',exact:true}).click();
  const explorer=page.getByRole('region',{name:'Environmental explorer'});
  await expect(explorer).toContainText('19 sols');
  await explorer.getByLabel('Station Environmental layer',{exact:true}).selectOption('grs-th');
  await expect(explorer).toContainText('not astronaut radiation dose');
  await explorer.getByLabel('Inspect environmental sample',{exact:true}).selectOption('th-1251');
  await expect(explorer.getByLabel('Station Environmental sample',{exact:true})).toContainText('ppm');
  await explorer.screenshot({path:info.outputPath('v06-composition.png')});
  await page.getByRole('button',{name:'Planetary atlas',exact:true}).click();await uiStationData(page);
  await expect(page.getByLabel('Atlas Environmental layer',{exact:true})).toHaveValue('grs-th');
  await expect(page.locator('.globe canvas')).toHaveAttribute('data-environment-layer','grs-th');
  await page.screenshot({timeout:60_000,path:info.outputPath('v06-atlas.png')});
  await page.getByRole('button',{name:'Data & history',exact:true}).click();
  await explorer.getByLabel('Station Environmental layer',{exact:true}).selectOption('mcs-temperature');
  await explorer.getByLabel('Inspect environmental sample',{exact:true}).selectOption({index:1});
  await expect(explorer.getByLabel('Station Environmental sample',{exact:true})).toContainText('2015-04-01');
  await explorer.getByLabel('Environmental sol',{exact:true}).selectOption('10');
  await explorer.getByLabel('Environmental hour',{exact:true}).fill('12');
  await expect(explorer.getByTestId('environment-temperature')).toContainText('249.38');
  await explorer.getByRole('button',{name:'Inspect simulated forecast',exact:true}).click();
  await expect(explorer.getByLabel('Environmental sol',{exact:true})).toHaveValue('29');
  await explorer.getByLabel('Station Environmental layer',{exact:true}).selectOption('site-temperature');
  await expect(explorer.getByRole('region',{name:'Station Environmental layers'})).toContainText('SIMULATED FORECAST');
  await explorer.getByRole('region',{name:'Simulated forecast'}).screenshot({path:info.outputPath('v06-forecast.png')});
  await nav(page).getByRole('button',{name:/Tablet/}).click();
  await expect(page.locator('.route-card.selected')).toHaveText(route!);
  await uiLayers(page);await page.locator('.tablet-environment > summary').click();
  await expect(page.getByLabel('Tablet Environmental layer',{exact:true})).toHaveValue('site-temperature');
  await expect(page.getByLabel('Tablet environmental sol',{exact:true})).toHaveValue('29');
  await page.getByLabel('Tablet Environmental layer',{exact:true}).selectOption('grs-k');
  await page.getByRole('img',{name:'Gale terrain selection map'}).screenshot({path:info.outputPath('v06-tablet-layer.png')});
  await page.getByRole('img',{name:'Gale terrain selection map'}).press('Enter');
  await expect(page.getByLabel('Tablet Environmental sample',{exact:true})).toContainText('wt%');
  await uiStation(page);
  await expect(explorer.getByLabel('Station Environmental layer',{exact:true})).toHaveValue('grs-k');
  await explorer.getByLabel('Environmental sol',{exact:true}).selectOption('10');
  // Select a real hour with both instruments before explicitly adopting a snapshot.
  const hour=await page.evaluate(async()=>{const c=await(await fetch('/environment/catalog.json')).json();return c.history.sols.find((s:any)=>s.sol===10).records.find((r:any)=>r.temperature!==null&&r.radiation!==null).hour as number;});
  await explorer.getByLabel('Environmental hour',{exact:true}).fill(String(hour));
  await explorer.getByRole('button',{name:'Use snapshot as fixed mission assumptions',exact:true}).click();
  await expect(explorer).toContainText('fixed manual mission assumptions');
  await nav(page).getByRole('button',{name:/Tablet/}).click();
  await expect(page.locator('.route-card')).toHaveCount(0);
  await uiAssumptions(page);await page.getByText('Departure conditions and limits',{exact:true}).click();
  await expect(page.getByLabel('Conditions mode',{exact:true})).toHaveValue('manual');
  await uiStation(page);
  await page.getByRole('button',{name:'Planetary atlas',exact:true}).click();await uiStationData(page);
  await page.getByRole('button',{name:'Reset globe view',exact:true}).click();
  await expect(page.locator('.globe canvas')).toHaveAttribute('data-environment-layer','grs-k');
  await expect.poll(async()=>{
    const encoded=(await page.locator('.globe canvas').screenshot()).toString('base64');
    return page.evaluate(async data=>{const img=new Image();img.src=`data:image/png;base64,${data}`;await img.decode();const canvas=document.createElement('canvas');canvas.width=100;canvas.height=100;const ctx=canvas.getContext('2d')!;ctx.drawImage(img,0,0,100,100);const pixels=ctx.getImageData(10,10,80,80).data;let colored=0;for(let i=0;i<pixels.length;i+=4)if(pixels[i]+pixels[i+1]+pixels[i+2]>130)colored++;return colored;},encoded);
  },{timeout:30_000}).toBeGreaterThan(100);
  await page.screenshot({timeout:60_000,path:info.outputPath('v06-global.png')});
  expect(errors).toEqual([]);
});

test('environmental package failure is recoverable and preserves the tablet',async({page})=>{
  let fail=true;
  await page.route('**/environment/catalog.json',route=>fail?route.fulfill({status:503,body:'unavailable'}):route.continue());
  await page.goto('/?demo=yellowknife');
  await uiStation(page);
  await page.getByRole('button',{name:'Data & history',exact:true}).click();
  await expect(page.getByRole('alert').filter({hasText:'Environmental layers unavailable'})).toBeVisible();
  fail=false;await page.getByRole('button',{name:'Retry environmental data',exact:true}).click();
  await expect(page.getByRole('region',{name:'Environmental explorer'})).toBeVisible();
  await page.setViewportSize({width:800,height:700});
  await page.getByLabel('Station Environmental layer',{exact:true}).selectOption('mcs-temperature');
  const explorer=page.getByRole('region',{name:'Environmental explorer'});
  expect(await explorer.evaluate(e=>e.scrollWidth<=e.clientWidth+2)).toBe(true);
});
